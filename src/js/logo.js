const COARSE_TONE = { b: 3, n: 2, d: 1 };

/**
 * Each logo as a descriptor the startup can draw:
 *   cols/rows    its own grid size
 *   w/h          how many text cells it covers on screen
 *   wordRow      text row (from the logo's top) where "[ KYN ]" goes
 *   eyes         grid area of the eyes (they light up in the animation)
 *   cell(c, r)   → [glyph, tone 0-3] or null for empty
 */
export const FINE = {
  kind: 'fine',
  cols: 105,
  rows: 109,
  w: 52,
  h: 27,
  wordRow: 16,
  eyes: { r0: 39, r1: 48, c0: 52, c1: 91 },
  cell(c, r) {
    const g = FINE_GLYPH[r]?.[c];
    return g && g !== ' ' ? [g, Number(FINE_TONE[r][c])] : null;
  },
};

export const COARSE = {
  kind: 'text',
  cols: 68,
  rows: 36,
  w: 68,
  h: 36,
  wordRow: 22,
  eyes: { r0: 12, r1: 15, c0: 35, c1: 57 },
  cell(c, r) {
    const ch = ART[r]?.[c];
    if (!ch || ch === ' ') return null;
    const glyph = ch === '#' ? 'M' : ch;
    return [glyph, ch === '.' || ch === ':' ? 0 : COARSE_TONE[TONE[r][c]] ?? 2];
  },
};
