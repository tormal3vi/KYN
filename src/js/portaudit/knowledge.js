/** Ports a quick check knocks on: every port described above, plus common extras. */
export const QUICK_PORTS = [...new Set([...KNOWLEDGE.keys(), ...EXTRA])].sort((a, b) => a - b);

export const RISK_ORDER = { high: 0, medium: 1, low: 2, info: 3 };

/**
 * Everything the UI shows about one open port.
 * context: { isSelf, onMac, localOnly }
 */
export function explain(port, context = {}) {
  const known = KNOWLEDGE.get(port);
  let entry = known;
  if (!entry) {
    entry = port >= 49152
      ? P(port, 'info', 'temporary app port', 'A port an app picked for itself (the "dynamic" range 49152–65535).',
        'Usually harmless: apps open these for syncing, games, or talking to their own helpers.',
        context.isSelf ? 'Check the app name; quit the app if you don\'t recognise it.' : 'Check which app or device feature uses it.')
      : P(port, 'low', 'unknown service', 'Not a well-known port, so KYN can\'t say for sure what it is.',
        'Most unknown ports are harmless app features, but it\'s worth knowing what each one is.',
        context.isSelf ? 'Look at the app name; quit or uninstall it if you don\'t recognise it.' : 'Look it up with the device\'s manual or the maker\'s support pages.');
  }
  const out = { ...entry, port, known: !!known };
  if (context.localOnly) {
    out.risk = 'info';
    out.why = `Only reachable from this computer itself (it listens on localhost), so other devices can't use it. ${entry.why}`;
  }
  if (context.onMac && entry.mac) out.fix = `${entry.fix} On this Mac: ${entry.mac}`;
  return out;
}
